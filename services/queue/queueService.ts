/** Canonical queue ticket statuses from queue-requirements.md. */
export type ClinicQueueStatus =
  | 'waiting'
  | 'in-consultation'
  | 'completed'
  | 'skipped'
  | 'overdue'
  | 'called'
  | 'serving';

/**
 * Older rows may use `called`/`serving`; normalize them to the canonical web
 * status before applying any transition.
 */
export function normalizeQueueStatus(status?: string | null): ClinicQueueStatus | null {
  const value = (status || '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
  if (value === 'waiting' || value === 'queued' || value === 'checked-in' || value === 'checked_in') {
    return 'waiting';
  }
  if (value === 'in-consultation' || value === 'in_consultation' || value === 'inc-consultation') {
    return 'in-consultation';
  }
  if (value === 'called' || value === 'serving') return value;
  if (
    value === 'completed' ||
    value === 'complete' ||
    value === 'done' ||
    value === 'finished' ||
    value === 'served' ||
    value === 'visited'
  ) {
    return 'completed';
  }
  if (value === 'skipped' || value === 'missed' || value === 'no-show' || value === 'noshow') {
    return 'skipped';
  }
  if (value === 'overdue') return value;
  return null;
}

/** True when a queue ticket represents a finished visit. */
export function isCompletedQueueTicket(ticket?: any): boolean {
  if (!ticket) return false;
  if (ticket.completed_at || ticket.completedAt) return true;
  return normalizeQueueStatus(ticket.status) === 'completed';
}

/** Appointment status implied by the latest linked queue ticket. */
export function getAppointmentStatusFromQueueTicket(ticket?: any): AppointmentStatus | null {
  if (!ticket) return null;
  const status = isCompletedQueueTicket(ticket) ? 'completed' : ticket.status;
  return mapQueueStatusToAppointmentStatus(status);
}

/**
 * Maps a canonical queue ticket status to the appointment status shown in the
 * mobile UI. `in-consultation` is the staff "Call" transition.
 */
export function mapQueueStatusToAppointmentStatus(
  status?: string | null,
): AppointmentStatus | null {
  const normalized = normalizeQueueStatus(status);
  if (!normalized) return null;

  switch (normalized) {
    case 'waiting':
      return 'queued';
    case 'in-consultation':
    case 'called':
    case 'serving':
      return 'called';
    case 'completed':
      return 'completed';
    case 'skipped':
      return 'missed';
    case 'overdue':
      return 'overdue';
    default:
      return null;
  }
}

/** Builds the compact queue ticket object stored on an appointment. */
export function toQueueTicketInfo(row: any): QueueTicketInfo {
  return {
    id: row.id,
    ticketNumber: row.ticket_number,
    queueSequence: row.queue_sequence,
    status: normalizeQueueStatus(row.status) || row.status || 'waiting',
    consultationRoom: row.consultation_room || 'Consultation Desk 1',
    servingVet: row.serving_vet || 'Dr. Helen Ann P. Tacandong, DVM',
    checkInTime: row.check_in_time || undefined,
  };
}

export interface ClinicQueueQrPayload {
  valid: boolean;
  date?: string;
  station?: string;
  token?: string;
  appointmentId?: string;
  petId?: string;
  serviceId?: string;
  raw: string;
}

/**
 * Parses clinic check-in QR code payloads generated by the CVO admin dashboard.
 * Example URL format:
 *   https://veterinaryoffice-cdo.vercel.app/queue-checkin?date=2026-11-11&station=cvo-carmen&token=cvo-queue-2026-11-11
 * Rejects unrelated URLs, Pet Passport verification tags, and Barangay Outreach QRs.
 */
export function parseClinicQueueQr(raw: string): ClinicQueueQrPayload {
  if (!raw) return { valid: false, raw: '' };
  const trimmed = raw.trim();

  try {
    // 1. Strict Clinic Queue URL check
    if (trimmed.startsWith('http://') || trimmed.startsWith('https://')) {
      const url = new URL(trimmed);
      const pathLower = url.pathname.toLowerCase();
      const hostLower = url.hostname.toLowerCase();

      // Reject Pet Passport tags and Barangay Outreach QRs
      if (
        pathLower.includes('/verify/pet') ||
        pathLower.includes('outreach') ||
        pathLower.includes('field-op') ||
        url.searchParams.has('opId') ||
        url.searchParams.has('op_id')
      ) {
        return { valid: false, raw: trimmed };
      }

      const date = url.searchParams.get('date') || undefined;
      const station = url.searchParams.get('station') || undefined;
      const token = url.searchParams.get('token') || undefined;
      const appointmentId =
        url.searchParams.get('appointmentId') ||
        url.searchParams.get('appointment_id') ||
        undefined;
      const petId =
        url.searchParams.get('petId') || url.searchParams.get('pet_id') || undefined;
      const serviceId =
        url.searchParams.get('serviceId') ||
        url.searchParams.get('service_id') ||
        undefined;

      const isCvoHost =
        hostLower.includes('veterinaryoffice-cdo') ||
        hostLower.includes('syncvet') ||
        hostLower === 'localhost';
      const isQueueRoute =
        pathLower.includes('queue-checkin') ||
        url.searchParams.get('type') === 'clinic-queue';
      const isQueueToken = Boolean(token && token.toLowerCase().startsWith('cvo-queue'));
      const hasValidDate = Boolean(date && /^\d{4}-\d{2}-\d{2}$/.test(date));

      const valid =
        hasValidDate &&
        (isQueueRoute || isQueueToken || (isCvoHost && Boolean(station)));

      return {
        valid,
        date: hasValidDate ? date : undefined,
        station:
          station === 'cvo-carmen'
            ? 'Carmen Central Clinic'
            : station || 'Carmen Central Clinic',
        token,
        appointmentId,
        petId,
        serviceId,
        raw: trimmed,
      };
    }

    // 2. Strict Clinic Queue JSON check
    if (trimmed.startsWith('{') && trimmed.endsWith('}')) {
      const parsed = JSON.parse(trimmed);
      if (parsed.opId || parsed.op_id || parsed.barangay || parsed.type === 'outreach') {
        return { valid: false, raw: trimmed };
      }

      // Appointment slips encode a JSON pass with only appointmentId + date;
      // they belong to the queue family even without a station/token signal.
      const appointmentPassId = parsed.appointmentId || parsed.appointment_id;
      const hasQueueSignal =
        parsed.type === 'clinic-queue' ||
        parsed.type === 'appointment' ||
        Boolean(parsed.station) ||
        Boolean(appointmentPassId) ||
        (typeof parsed.token === 'string' && parsed.token.toLowerCase().startsWith('cvo-queue'));

      if (
        hasQueueSignal &&
        typeof parsed.date === 'string' &&
        /^\d{4}-\d{2}-\d{2}$/.test(parsed.date)
      ) {
        return {
          valid: true,
          date: parsed.date,
          station:
            parsed.station === 'cvo-carmen'
              ? 'Carmen Central Clinic'
              : parsed.station || 'Carmen Central Clinic',
          token: parsed.token,
          appointmentId: parsed.appointmentId || parsed.appointment_id,
          petId: parsed.petId || parsed.pet_id,
          serviceId: normalizeServiceId(parsed.serviceId || parsed.service_id),
          raw: trimmed,
        };
      }
    }
  } catch {
    // Ignore URL/JSON parse errors
  }

  return {
    valid: false,
    raw: trimmed,
  };
}

export type QueueEligibilityResult =
  | { eligible: true; alreadyQueued?: boolean; ticket?: QueueTicketInfo }
  | {
      eligible: false;
      reason:
        | 'invalid_qr'
        | 'invalid_date'
        | 'overdue'
        | 'future'
        | 'completed'
        | 'cancelled'
        | 'wrong_appointment';
      message: string;
    };

/**
 * Validates whether an appointment can be checked into the clinic queue with the scanned QR.
 */
export function validateCheckInEligibility(
  appointment: Appointment,
  qrPayload: ClinicQueueQrPayload,
): QueueEligibilityResult {
  if (!qrPayload.valid || !qrPayload.date) {
    return {
      eligible: false,
      reason: 'invalid_qr',
      message: 'This QR code is not a valid Clinic Queue Check-in station.',
    };
  }

  const today = todayISO();
  const qrDate = qrPayload.date;

  // The QR is only valid for today's clinic schedule
  if (qrDate !== today) {
    return {
      eligible: false,
      reason: 'invalid_date',
      message: `This Check-in QR is dated ${qrDate}. It is only valid for clinic hours today (${today}).`,
    };
  }

  const appointmentStatus = normalizeAppointmentStatus(appointment.status);
  if (appointmentStatus === 'completed') {
    return {
      eligible: false,
      reason: 'completed',
      message: `The visit for ${appointment.petName} has already been completed.`,
    };
  }

  if (appointmentStatus === 'cancelled') {
    return {
      eligible: false,
      reason: 'cancelled',
      message: `This appointment was cancelled and cannot be queued.`,
    };
  }

  // Per queue requirements, skipped/overdue tickets may rejoin at the end of
  // the line by scanning again on the scheduled day.
  if (
    (appointmentStatus === 'overdue' || appointmentStatus === 'missed') &&
    appointment.date !== qrDate
  ) {
    return {
      eligible: false,
      reason: 'overdue',
      message: `This appointment was scheduled for ${appointment.date} and is already overdue/missed.`,
    };
  }

  // Enforce optional appointment / pet / service binding if embedded in the scanned QR
  if (qrPayload.appointmentId && qrPayload.appointmentId !== appointment.id) {
    return {
      eligible: false,
      reason: 'wrong_appointment',
      message: 'This QR code is issued for a different appointment.',
    };
  }
  if (qrPayload.petId && qrPayload.petId !== appointment.petId) {
    return {
      eligible: false,
      reason: 'wrong_appointment',
      message: `This QR code belongs to a different pet, not ${appointment.petName}.`,
    };
  }
  if (qrPayload.serviceId && qrPayload.serviceId !== appointment.serviceId) {
    return {
      eligible: false,
      reason: 'wrong_appointment',
      message: 'This QR code is issued for a different clinic service.',
    };
  }

  // If already queued or called
  if (
    appointmentStatus === 'queued' ||
    appointmentStatus === 'checked_in' ||
    appointmentStatus === 'called' ||
    appointmentStatus === 'serving'
  ) {
    return {
      eligible: true,
      alreadyQueued: true,
      ticket: appointment.queueTicket,
    };
  }

  // Compare scheduled appointment date with QR date
  if (appointment.date < qrDate) {
    return {
      eligible: false,
      reason: 'overdue',
      message: `This appointment was scheduled for ${appointment.date} and was not attended on that day. Status is now Overdue.`,
    };
  }

  if (appointment.date > qrDate) {
    return {
      eligible: false,
      reason: 'future',
      message: `Your appointment is scheduled for ${appointment.date}. Clinic check-in opens on your scheduled visit day.`,
    };
  }

  return { eligible: true };
}

export interface CheckInAppointmentParams {
  appointment: Appointment;
  stationName?: string;
  user?: any;
  pet?: any;
}

/**
 * Registers an appointment into the Supabase queue_tickets table and updates the appointment status.
 */
export async function checkInAppointmentToQueue({
  appointment,
  stationName = 'Carmen Central Clinic',
  user,
  pet,
}: CheckInAppointmentParams): Promise<QueueTicketInfo> {
  const today = todayISO();

  // 1. Duplicate check-in is idempotent while a ticket is still active.
  // Skipped/overdue rows are intentionally excluded so a rescan rejoins at the
  // end of the line.
  try {
    const { data: activeRows, error } = await supabase
      .from('queue_tickets')
      .select('*')
      .eq('date', today)
      .in('status', ['waiting', 'in-consultation']);

    if (!error && Array.isArray(activeRows)) {
      const existing = activeRows.find(
        (row: any) =>
          row.appointment_id === appointment.id ||
          (Boolean(appointment.petId) && row.pet_id === appointment.petId),
      );
      if (existing) return toQueueTicketInfo(existing);
    }
  } catch (err) {
    console.warn('Error checking existing queue ticket:', err);
  }

  // 2. Allocate the sequence server-side when the RPC is deployed. The local
  // count remains a compatibility fallback for older backends.
  let nextSequence = 1;
  try {
    const { data: rpcSequence, error: rpcError } = await (supabase as any).rpc(
      'allocate_queue_ticket_sequence',
      { p_date: today },
    );

    if (!rpcError && typeof rpcSequence === 'number') {
      nextSequence = rpcSequence;
    } else {
      const { count, error } = await supabase
        .from('queue_tickets')
        .select('*', { count: 'exact', head: true })
        .eq('date', today);
      if (!error && typeof count === 'number') nextSequence = count + 1;
    }
  } catch (err) {
    console.warn('Error allocating queue sequence:', err);
  }

  const ticketNumber = `Q-${String(nextSequence).padStart(3, '0')}`;
  const now = new Date();
  const checkInTime = now.toLocaleTimeString([], { hour: 'numeric', minute: '2-digit' });
  const ticketId = `ticket_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`;
  const encounterNo = `ENC-${now.getFullYear()}-${Math.floor(1000 + Math.random() * 9000)}`;

  const serviceTitle =
    appointment.serviceId === 'vaccination'
      ? 'Anti-Rabies Immunization & Health Check'
      : appointment.serviceId === 'spay-neuter'
      ? 'Spay & Neuter (Kapon) Surgery'
      : 'Clinical Consultation & Treatment';

  const ticketInfo: QueueTicketInfo = {
    id: ticketId,
    ticketNumber,
    queueSequence: nextSequence,
    status: 'waiting',
    consultationRoom: 'Consultation Desk 1',
    servingVet: 'Dr. Helen Ann P. Tacandong, DVM',
    checkInTime,
  };

  // 3. Insert into queue_tickets table in Supabase
  try {
    const { error: insertErr } = await supabase.from('queue_tickets').insert({
      id: ticketId,
      date: today,
      ticket_number: ticketNumber,
      queue_sequence: nextSequence,
      appointment_id: appointment.id,
      encounter_no: encounterNo,
      owner_id: user?.id || appointment.ownerId || null,
      owner_name: user?.fullName || 'Resident Owner',
      owner_contact: user?.primaryPhoneNumber?.phoneNumber || user?.phone || null,
      owner_barangay: 'Carmen',
      pet_id: appointment.petId || null,
      pet_name: appointment.petName,
      pet_photo_url: pet?.photoUrl || null,
      species: pet?.species ? (pet.species === 'cat' ? 'Cat' : 'Dog') : 'Companion',
      breed: pet?.breed || 'Domestic Companion',
      service_id: appointment.serviceId,
      service_title: serviceTitle,
      status: 'waiting',
      serving_vet: 'Dr. Helen Ann P. Tacandong, DVM',
      consultation_room: 'Consultation Desk 1',
      check_in_time: checkInTime,
      checked_in_at: now.toISOString(),
      checked_in_via: 'qr',
      notes: `[Checked in: Ticket ${ticketNumber}]`,
    });

    if (insertErr) {
      console.warn('Queue ticket insert error in Supabase:', insertErr.message);
    }
  } catch (err) {
    console.warn('Queue ticket insert exception:', err);
  }

  // 4. Update appointments table in Supabase
  try {
    const appendedNotes = appointment.notes
      ? `${appointment.notes} | [Checked in: Ticket ${ticketNumber}]`
      : `[Checked in: Ticket ${ticketNumber}]`;

    const { error: apptErr } = await supabase
      .from('appointments')
      .update({
        status: 'queued',
        notes: appendedNotes,
        updated_at: now.toISOString(),
      })
      .eq('id', appointment.id);

    if (apptErr) {
      console.warn('Appointment status update error:', apptErr.message);
    }
  } catch (err) {
    console.warn('Appointment status update exception:', err);
  }

  return ticketInfo;
}

/**
 * Marks an appointment as overdue in Supabase when its scheduled date has passed.
 */
export async function markAppointmentOverdue(appointmentId: string): Promise<void> {
  try {
    const { error } = await supabase
      .from('appointments')
      .update({
        status: 'overdue',
        updated_at: new Date().toISOString(),
      })
      .eq('id', appointmentId);

    if (error) {
      console.warn('Error marking appointment overdue:', error.message);
    }
  } catch (err) {
    console.warn('Exception marking appointment overdue:', err);
  }
}

/**
 * Marks an appointment and its queue ticket as completed, moving it into visit history.
 */
export async function completeQueueAppointment(
  appointmentId: string,
  ticketNumber?: string,
): Promise<void> {
  const now = new Date().toISOString();
  try {
    await supabase
      .from('appointments')
      .update({
        status: 'completed',
        updated_at: now,
      })
      .eq('id', appointmentId);

    if (ticketNumber) {
      await supabase
        .from('queue_tickets')
        .update({
          status: 'completed',
          completed_at: now,
          updated_at: now,
        })
        .eq('ticket_number', ticketNumber);
    }
  } catch (err) {
    console.warn('Error completing appointment in Supabase:', err);
  }
}

/**
 * Staff "Call" transition: waiting → in-consultation. The appointment is
 * marked `called` for the owner UI while the ticket keeps the canonical status.
 */
export async function callQueueAppointment(
  appointmentId: string,
  ticketNumber?: string,
): Promise<void> {
  const now = new Date().toISOString();
  try {
    await supabase
      .from('appointments')
      .update({
        status: 'called',
        updated_at: now,
      })
      .eq('id', appointmentId);

    if (ticketNumber) {
      await supabase
        .from('queue_tickets')
        .update({
          status: 'in-consultation',
          called_at: now,
          updated_at: now,
        })
        .eq('ticket_number', ticketNumber);
    }
  } catch (err) {
    console.warn('Error calling appointment in Supabase:', err);
  }
}

/**
 * Staff "Skip" transition: active → skipped; the linked appointment becomes
 * `missed` and the owner can rescan to rejoin at the end of the line.
 */
export async function skipQueueAppointment(
  appointmentId: string,
  ticketNumber?: string,
): Promise<void> {
  const now = new Date().toISOString();
  try {
    await supabase
      .from('appointments')
      .update({ status: 'missed', updated_at: now })
      .eq('id', appointmentId);

    if (ticketNumber) {
      await supabase
        .from('queue_tickets')
        .update({ status: 'skipped', updated_at: now })
        .eq('ticket_number', ticketNumber);
    }
  } catch (err) {
    console.warn('Error skipping appointment in Supabase:', err);
  }
}

